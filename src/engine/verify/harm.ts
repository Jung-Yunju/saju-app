const NEG_RE =
  /^[^,.!?]{0,6}?(?:(?:결코|절대|전혀|그리|크게|쉽게|별로|딱히|아직|굳이|함부로)\s?)?(?:지\s?(?:는|도|만)?\s?(?:않|말|마|못)|(?:은|는|이|가|도|할|될|날|일|될 일|할 일|날 일)?\s?(?:일은|일이|일도|걱정은|걱정이|건|것은|게)?\s?(?:(?:결코|절대|전혀|그리|크게|별로|딱히)\s?)?(?:없|아니)|없이|않도록|않게|없도록|없게|안 (?:된|한|난|생|올|일어)|못 (?:한|된|난))/
const COND_RE = /^[^,.!?]{0,10}?(?:면|으면|거든|더라도|어도|아도|해도|라도|다면|ㄴ다면|는다면|더라면)(?=[\s,]|$)/
