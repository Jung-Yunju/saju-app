const QUOTE_ASSERT_AFTER_RE = /^\s?(?:나온다|나와 있|보인다|보여|본다|봐야|읽힌다|적혀 있|쓰여 있|되어 있|돼 있|정해져 있|해석된다|풀이된다|짚인다|여긴다|봐도 된|할 수 있다|해도 과언|한다\.|했다\.)/
const REPORT_AFTER_RE = /^\s?(?:했지|했잖|했구나|했던|했으니|했는데|했다지|하더구나|하더라|했어|털어놓|얘기했|이야기했|말했|들려주|썼지|적었지|적어 줬)/
const QUESTION_RE = /^[^.!?]{0,10}?(?:ㄹ까|을까|ㄹ지|을지|는지|ㄴ지|는가|ㄴ가|느냐|냐|나요|니\?|까\?)/
const MAYBE_RE = /^[^.!?]{0,10}?(?:ㄹ지|을지|는지|ㄴ지)\s?도?\s?(?:모르|모른|몰라|모를)|^[^.!?]{0,10}?(?:ㄹ지|을지)도\s?/
const WORRY_AFTER_RE = /(?:ㄹ까|을까|는지|ㄹ지|을지)\s?(?:봐|싶어|싶|걱정|두려|무서|겁|조마|마음 졸|불안|염려|애가 타|속 끓)/
const UNCERTAIN_AFTER_RE = /(?:ㄹ지|을지|는지|ㄴ지)(?:는|도)?\s?(?:할미도|나도|누구도|아무도|사주로는?|사주도|사주가)?\s?(?:몰라|모르|모른|모를|알 수 없|알 수가 없)/
const PAST_RE = /^(?:ㅆ|ㄴ\s|어\s?버렸|었|았|였|했|셨|났|겪었|당했|받았|치렀|섰|졌|갔|왔|쳤|렸|던)|^[^,.!?]{0,8}?(?:었|았|였|했|났|겪었|당했|받았|치렀|섰|졌|갔|왔|쳤|렸|셨)(?:다|고|던|지|어|으니|는데|구나|더라|을 때|을 적)/
const PAST_CLAIM_RE = /^[^,.!?]{0,10}?(?:ㅆ을|었을|았을|였을|했을|났을|섰을|졌을|셨을)\s?(?:것|거|수|테)/
const TOPIC_NOUN_RE = /^\s?(?:이야기|얘기|문제|고민|생각|걱정|말|여부|상담|소식을 들|을 고민|를 고민|을 생각|를 생각|을 망설|를 망설|이야기를|얘기를|문제를|문제로|문제는|고민을|고민이|걱정을|걱정이|생각을|생각이|에 대한|에 관한|(?:과 )?같은 일(?!(?:이|을|도|이야|은)?\s?(?:생|일어|닥|찾아|오|온|올|와|있|겪|당|벌어|터|든|들))|같은 말|같은 소리)/
/** 금지 주제를 "다루지 않는다·믿지 마라" 식으로 걷어 내는 서술(일치 구간 뒤 문장 안 어디든) */
const META_PRED_RE =
  /대신 (?:내리|정하|골라 주|골라주|정해 주|정해주|결정하)(?:지|지는|지도|ㄹ 수|을 수)\s?(?:않|못|없|말|마)|(?:짚|말하|정하|점치|예언하|맞히|가리|답하|단정하|못 박|미리 알|알려 주|알려주|봐 주|봐주|내다보|예측하|따지)(?:지|지는|지도|ㄹ 수|을 수)\s?(?:않|못|없|말|마)|(?:말|이야기|얘기)(?:은|는|을|를)?\s?(?:하지 않|안 한|않는)|정해져 있지 않|정해진 (?:게|것이) 아니|적혀 있지 않|나와 있지 않|쓰여 있지 않|(?:믿지|겁먹지|걱정하지|두려워하지|신경 쓰지|마음 쓰지|떨지|휘둘리지)\s?(?:마|말|않아도)|걱정 (?:마|말|안 해도)|겁낼 (?:것|거|일) 없|겁주는|허튼|근거 없는|함부로 하는|사주(?:가|로|에|로는|에는)\s?(?:정하|정해|나오|적혀|알|보이)(?:지|는 게)?\s?(?:않|못|없|아니)|사주로 (?:가릴|알|볼|정할) (?:일|수)(?:이|가)? 아니|사주로는? (?:알 수 없|못 본|보지 않|정하지 않)|할미는 (?:그런|그 같은|이런)|그런 (?:말|소리|풀이|예언)(?:은|는|을)/
/** 단정형 맺음 — 이 꼴로 바로 끝나면 뒤의 메타 말이 있어도 단정이다 */
const FINITE_ASSERT_RE = /^(?:ㄴ다|는다|다|겠다|ㄹ 것이다|을 것이다|ㄹ 거다|을 거다|ㄹ 거야|게 된다|게 될 것|어 버린다|ㄴ단다|는단다|단다)\s*(?:,|\.|!|만|마는|$)/
const HEDGE_RE = /(?:수 있|수도 있|수가 있|ㄹ지도|을지도|기 쉽|가능성|우려|염려가 있|위험이 있|위험하|조심|주의|살펴|대비|챙겨|조짐|기미|낌새|않을까|듯하|것 같|거 같|모양이|보인다|비친다|비치|올 수|생길 수)/
const SHORT_RE = /^[^,.!?]{0,4}?(?:길지 않|길지 못|길지가 않|오래\s?가지 않|오래\s?못|많지 않|얼마 (?:남지 않|안 남|못 남)|넉넉하지 않|짧)/
const FATE_RE = /^\s?(?:수|살|운|기운|조짐|팔자|기미)?\s?(?:가|이)\s?(?:들었|들어 있|끼었|끼어 있|있다|있어|비친다|비쳐|보인다|서려|깔려|따른다|따라)/
/** 되짚기: 앞에 "네가 말한·겪었다는·지난" 등 */
const REPORT_BEFORE_RE = /(?:네가|니가|너는|너도|당신이)?\s?(?:말한|말했던|말해 준|말해준|들려준|털어놓은|겪은|겪었던|겪었다는|겪어 낸|지나온|지나간|지난|견뎌 낸|이겨 낸|버텨 낸|치른|치렀던)\s?[^.!?]{0,6}$/

/**
 * 해로운 낱말을 다스리는 서술의 양태. tail = 일치 구간 뒤 글(끝 음절 받침을 자모로 복원한 머리 포함), before = 앞 글.
 * 우선순위: 되짚기 > 단정 맺음 > (가장 먼저 나오는) 부정·조건·인용·질문 > 과거 > 메타 서술 > 기본 단정/가능성.
 */
export function modalityOf(tail: string, before: string, noun: boolean): Modality {
  // 음절에 묻힌 받침을 드러낸다: "날지" → "날ㄹ지", "올까" → "올ㄹ까", "한지" → "한ㄴ지"(어미 판정 정규식이 자모로 찾는다)
  const t = tail
    .replace(/^\s+/, (m) => (m.length > 1 ? " " : m))
    .replace(/[가-힣](?=까|지(?!\s?(?:는|도|만)?\s?(?:않|못|말|마)))/g, (c) => {
      const d = decompose(c)
      return d?.t === 8 ? c + "ㄹ" : d?.t === 4 ? c + "ㄴ" : c
    })
  if (REPORT_BEFORE_RE.test(before)) return "report"
  // "이혼수가 들었다", "사고수가 있다", "상문살이 끼었다" — 운명 단정(과거형이어도 지금의 단정)
  if (FATE_RE.test(t)) return "assert"
  // "수명이 길지 않다", "함께할 날이 얼마 남지 않았다" — 양을 부정한 말은 부정이 아니라 짧다는 단정
  if (SHORT_RE.test(t)) return /^[^,.!?]{0,14}?(?:면|다면|거든)(?=[\s,]|$)/.test(t) ? "cond" : "assert"
  if (noun && TOPIC_NOUN_RE.test(t)) return "topic"
  if (FINITE_ASSERT_RE.test(t.replace(/^(?:을|를|이|가|은|는)?\s?(?:하|당하|겪|맞|치르|받|생기|나|오|닥치|찾아오|들|얻|앓|걸리)?/, ""))) {
    // "이혼한다." "사고가 난다," — 맺음이 단정이면 뒤 메타 말과 무관하게 단정
    if (!/^[^,.!?]{0,4}지\s?(?:않|말|마|못)/.test(t)) return "assert"
  }
  const cand: [Modality, number][] = []
  const at = (re: RegExp, mo: Modality) => {
    const m = re.exec(t)
    if (m) cand.push([mo, m.index + m[0].length])
  }
  at(NEG_RE, "neg")
  at(COND_RE, "cond")
  const q = QUOTE_RE.exec(t)
  if (q) {
    const after = t.slice(q.index + q[0].length)
    cand.push([REPORT_AFTER_RE.test(after) ? "report" : QUOTE_ASSERT_AFTER_RE.test(after) ? "hedge" : "meta", q.index + q[0].length])
  }
  const mb = MAYBE_RE.exec(t)
  if (mb) cand.push(["hedge", mb.index + mb[0].length])
  else {
    const qm = QUESTION_RE.exec(t)
    if (qm) cand.push([WORRY_AFTER_RE.test(t) ? "worry" : UNCERTAIN_AFTER_RE.test(t) ? "uncertain" : /[?？]|느냐|냐\s*$|나요/.test(t) ? "question" : "meta", qm.index + qm[0].length])
  }
  if (cand.length) {
    cand.sort((a, b) => a[1] - b[1])
    return cand[0][0]
  }
  if (PAST_CLAIM_RE.test(t)) return "pastClaim"
  if (PAST_RE.test(t)) return "past"
  if (META_PRED_RE.test(t)) return "meta"
  if (/[?？]\s*$/.test(t)) return "question"
  return HEDGE_RE.test(t.slice(0, 30)) ? "hedge" : "assert"
}

export interface HarmHit {
  cat: HarmCategory
  severe: boolean
  index: number
  length: number
  modality: Modality
}

/** 괄호 한자 주석 지우기("명(命)이 다한다" → "명이 다한다"). 간지 한자 주석은 남긴다(병(丙)은 병이 아니다) */
export function stripGlosses(s: string): string {
  return s.replace(/([가-힣])\s?[(（]([一-鿿]{1,6})[)）]/g, (m, h: string, hz: string) => (/[甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉戌亥]/.test(hz) ? m : h))
}

/** 간지 한글 읽기 가리기: "병오(丙午)", "병(丙)", "병화", "병자년", "정사 대운" — '병이 오다'·'병자(환자)'로 읽히지 않게 */
const GZ_HANJA = "[甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉戌亥]"
const READING_GLOSS_RE = new RegExp(`([가-힣]{1,3})(\\s?[(（]${GZ_HANJA}{1,2}[木火土金水]?[)）])`, "g")
const HANGUL_PILLAR_RE = /(?<![가-힣])([갑을병정무기경신임계][자축인묘진사오미신유술해])(?=\s?(?:년|일주|월주|연주|시주|대운|세운|생|띠))/g
const HANGUL_ELEMENT_RE = /(?<![가-힣])(갑목|을목|병화|정화|무토|기토|경금|신금|임수|계수)(?![가-힣]{2})/g
const READING_SYL = new Set([..."갑을병정무기경신임계자축인묘진사오미신유술해목화토금수"])
export function maskGanzhiReadings(s: string): string {
  return s
    .replace(READING_GLOSS_RE, (m, h: string, rest: string) => ([...h].every((c) => READING_SYL.has(c)) ? "□".repeat(h.length) + rest : m))
    .replace(HANGUL_PILLAR_RE, (m) => "□".repeat(m.length))
    .replace(HANGUL_ELEMENT_RE, (m) => "□".repeat(m.length))
}

export function findHarms(sentence: string): HarmHit[] {
  const text = maskGanzhiReadings(stripGlosses(sentence)).replace(HARM_IDIOMS_RE, (m) => "□".repeat(m.length))
  const out: HarmHit[] = []
  for (const p of HARM_PATTERNS) {
    p.re.lastIndex = 0
    for (const m of text.matchAll(p.re)) {
      const i = m.index ?? 0
      if (m[0].length === 0) continue
      if (out.some((o) => i < o.index + o.length && o.index < i + m[0].length)) continue
      // "댁으로 돌아가실 때"(귀가)
      if (/^돌아/.test(m[0]) && /((댁|집|고향|본가|자리|제자리|숙소|회사|학교|일터|방|곳|데)(으로|로|에)|으로|쪽으로)\s*$/.test(text.slice(Math.max(0, i - 8), i))) continue
      const rest = text.slice(i + m[0].length, i + m[0].length + 40)
      const tail = tailOf(m[0].slice(-1), p.stemLast, rest, !p.noun)
      const before = text.slice(Math.max(0, i - 20), i)
      out.push({ cat: p.cat, severe: p.severe, index: i, length: m[0].length, modality: modalityOf(tail, before, !!p.noun) })
    }
  }
  return out.sort((a, b) => a.index - b.index)
}
