export const PROMPT_VERSION = "prompts@0.4.0"

export interface SystemOptions {
  voice?: Voice
  tone?: ToneStrength
  /** 기본 GRANDMA_NAME(미정이면 null) */
  grandmaName?: string | null
  /** 위기 문안의 부름말에 쓰는 호칭(사실표 subject.addressAs). 실명은 넣지 않는다 */
  addressAs?: string
}

/** 사실표의 선택 칸 style.voice("담백"/"plain")를 읽는다. 없으면 할미 목소리 */
export function resolveVoice(facts: FactSheet): Voice {
  const v = (facts as FactSheetWithExtras).style?.voice
  return v === "담백" || v === "plain" ? "plain" : "halmi"
}

/** 사용자 사실 toneStrength(gentle·balanced·direct). 없으면 balanced */
export function resolveTone(facts: FactSheet): ToneStrength {
  const f = facts.personal.userFacts.find((x) => x.topic === "toneStrength")
  const v = f?.value
  if (v === "gentle" || v === "부드럽게 돌려서") return "gentle"
  if (v === "direct" || v === "솔직하게 짚어서") return "direct"
  return "balanced"
}

